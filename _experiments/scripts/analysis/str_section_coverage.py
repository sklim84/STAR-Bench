#!/usr/bin/env python3
"""tab:str_section_coverage - what the gold STR summaries cover, section by section.

The manuscript reports how completely the ground-truth STR drafts fill the
narrative sections of the Korean STR form. The number is a property of the
benchmark data, not of any model, so it is computed here from
`benchmarks_multiturn/cases_str_workflow.json` and the section patterns the
scorer uses, rather than transcribed. A hand-kept copy goes stale the first
time a gold summary is edited, and the summaries have been edited since.

    python -m _experiments.scripts.analysis.str_section_coverage [--out <dir>]

Writes `tab-str-section-coverage.tex` beside the other generated tables.
"""

import argparse
import json
import statistics as st
import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[3]
for _p in (str(_ROOT), str(_ROOT / "_experiments" / "scripts")):
    if _p not in sys.path:
        sys.path.insert(0, _p)

from _experiments.scripts.RQ_str_generation_quality import section_coverage  # noqa: E402

CASES = _ROOT / "benchmarks_multiturn" / "cases_str_workflow.json"
DEFAULT_OUT = _ROOT / "_experiments" / "paper_tables"

# The scorer's key for each section, and the name the manuscript prints for it.
# The two were allowed to drift apart once, and the prose then named sections
# that no row carried.
ROWS = [
    ("VII.1 subjects", "Transacting parties"),
    ("VII.2 date", "Date and time"),
    ("VII.3 place", "Institution and branch"),
    ("VII.4 instrument", "Instrument and channel"),
    ("VII.5 method", "Transaction method"),
    ("VII.6 grounds", "Grounds for suspicion"),
    ("VII.7 6W summary", "Overall assessment (6W)"),
]


def gold_summaries() -> list[str]:
    """The `summary` argument of every gold generate_str call, one per scenario."""
    out = []
    for case in json.loads(CASES.read_text(encoding="utf-8")):
        for turn in case["turns"]:
            for call in turn.get("tool_calls") or []:
                summary = (call.get("arguments") or {}).get("summary")
                if summary:
                    out.append(summary)
    return out


def _fmt(value: float, places: int = 3) -> str:
    """The leading zero is kept, because this table reaches 1.000."""
    return f"{value:.{places}f}"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()

    summaries = gold_summaries()
    if not summaries:
        raise SystemExit(f"no gold STR summaries in {CASES}")
    scored = [section_coverage(s) for s in summaries]
    n_scenarios = len(json.loads(CASES.read_text(encoding="utf-8")))

    lines = [
        "% generated by _experiments/scripts/analysis/str_section_coverage.py",
        f"% {len(summaries)} gold STR summaries of {n_scenarios} scenarios",
        "\\begin{table}[t]", "\\centering", "\\footnotesize",
        "\\setlength{\\tabcolsep}{5pt}",
        "\\caption{Narrative section coverage of the ground-truth STR draft summaries "
        f"($n{{=}}{len(summaries)}$ scenarios whose gold ends in an STR). Coverage is the share of "
        "summaries that satisfy the section's keywords; the overall-assessment row scores the six "
        "5W1H items and so takes fractional values.}",
        "\\label{tab:str_section_coverage}",
        "\\begin{tabular}{lrr}", "\\toprule",
        "\\textbf{Section} & \\textbf{Coverage (\\%)} & \\textbf{Mean score} \\\\",
        "\\midrule",
    ]
    means = []
    for key, name in ROWS:
        values = [row[key] for row in scored]
        coverage = 100 * sum(1 for v in values if v > 0) / len(values)
        mean = st.mean(values)
        means.append(mean)
        lines.append(f"{name} & {coverage:.1f} & {_fmt(mean)} \\\\")
    overall = st.mean(st.mean(row[k] for k, _ in ROWS) for row in scored)
    lines += ["\\midrule",
              f"\\textbf{{Average}} & & \\textbf{{{_fmt(overall)}}} \\\\",
              "\\bottomrule", "\\end{tabular}", "\\end{table}"]

    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "tab-str-section-coverage.tex").write_text("\n".join(lines) + "\n",
                                                           encoding="utf-8")
    print(f"tab-str-section-coverage.tex: {len(summaries)} gold summaries of "
          f"{n_scenarios} scenarios, average {overall:.3f}")
    for (key, name), mean in zip(ROWS, means):
        print(f"  {name:<26} {mean:.3f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
