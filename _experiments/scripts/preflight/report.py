"""The written report: every gate, every version and hash, every command.

`--report` writes `_experiments/scripts/preflight/reports/preflight_report.md`
and `.json`, both tracked, so the report a co-author reads is the one in the
checkout they cloned. It exists so that a co-author whose run is blocked can
paste one file and the person reading it can see which gate failed, on which
checkout, and which command to run to see it again.

The report is regenerated, never edited. Regenerating it modifies two tracked
files, so commit them (or discard them) before the next run: gate 1 reads a
modified tracked file as a dirty tree.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

from .gate import GateResult, REPORT_DIR

REPORT_PATH = REPORT_DIR / "preflight_report.md"
JSON_PATH = REPORT_DIR / "preflight_report.json"


def as_json(results: list[GateResult], *, command: str, versions: dict) -> dict:
    return {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "command": command,
        "ok": all(r.ok for r in results),
        "versions": versions,
        "gates": [r.as_dict() for r in results],
    }


def collect_versions(ctx) -> dict:
    """The facts a failing report has to carry: what was run, and against what."""
    from .gate import run_command

    probe = run_command([ctx.platform_python, "-m", "_experiments.scripts.preflight._probe"],
                        cwd=ctx.root, env=ctx.env, timeout=600)
    try:
        info = json.loads(probe.stdout.strip().splitlines()[-1])
    except (ValueError, IndexError):
        info = {}
    platform = info.get("platform") or {}
    return {
        "star_bench_commit": info.get("star_bench_commit"),
        "star_bench_dirty": info.get("star_bench_dirty"),
        "star_bench_root": str(ctx.root),
        "platform_commit": platform.get("platform_commit"),
        "platform_dirty": platform.get("platform_dirty"),
        "platform_root": str(ctx.platform_root),
        "data_sha256": platform.get("data_sha256"),
        "db_sha256": platform.get("db_sha256"),
        "model_file_sha256": platform.get("model_file_sha256"),
        "platform_prompt_sha256": platform.get("system_prompt_sha256"),
        "platform_tools_sha256": platform.get("tools_sha256"),
        "streamlit_stubbed": platform.get("streamlit_stubbed"),
        "library_versions": platform.get("library_versions"),
        "python": ctx.python,
        "platform_python": ctx.platform_python,
    }


def _readable(command: str, versions: dict) -> str:
    """The command with the interpreter path replaced, so the report is pasteable.

    Which interpreter it was is in the versions table; the command itself reads
    the way a co-author would type it.
    """
    for key in ("platform_python", "python"):
        path = versions.get(key)
        if path and path != "python":
            command = command.replace(path, "python")
    return command


def _per_tool_tables(result: GateResult) -> list[str]:
    """The gold gate's per-tool counts, which is what a data owner reads first."""
    lines: list[str] = []
    for check in result.checks:
        per_tool = (check.data or {}).get("per_tool")
        if not per_tool:
            continue
        lines.append(f"<details><summary>{check.name}: per tool</summary>")
        lines.append("")
        lines.append("| tool | ok | empty | error | skipped |")
        lines.append("|---|---:|---:|---:|---:|")
        for tool, counts in sorted(per_tool.items()):
            lines.append(f"| {tool} | {counts['ok']} | {counts['empty']} | {counts['error']} "
                         f"| {counts['skipped']} |")
        lines.append("")
        lines.append("</details>")
        lines.append("")
    return lines


def _hash_rows(versions: dict) -> list[tuple[str, str]]:
    keys = ("star_bench_commit", "platform_commit", "data_sha256", "db_sha256",
            "model_file_sha256", "platform_prompt_sha256", "platform_tools_sha256")
    rows = []
    for key in keys:
        value = versions.get(key)
        rows.append((key, value if value else "not readable"))
    return rows


def write_markdown(results: list[GateResult], *, command: str, versions: dict,
                   path: Path | None = None) -> Path:
    path = Path(path or REPORT_PATH)
    lines: list[str] = []
    ok = all(r.ok for r in results)
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    lines.append("# Pre-flight report")
    lines.append("")
    lines.append(f"`{command}` on {stamp}: **{'all gates pass' if ok else 'FAILED'}**.")
    lines.append("")
    lines.append("Generated by `python -m _experiments.scripts.preflight.run --all --report`. "
                 "Regenerate it rather than editing it.")
    lines.append("")

    lines.append("## Gates")
    lines.append("")
    lines.append("| | Gate | Checks | Time |")
    lines.append("|---|---|---|---|")
    for result in results:
        status = "SKIP" if result.skipped else ("pass" if result.ok else "**FAIL**")
        passed = sum(1 for c in result.checks if c.ok)
        lines.append(f"| {result.number} | {result.title} | {status}, {passed}/{len(result.checks)}"
                     f" | {result.elapsed_s:.1f}s |")
    lines.append("")

    failures = [(r, c) for r in results for c in r.checks if not c.ok]
    if failures:
        lines.append("## What failed")
        lines.append("")
        for result, check in failures:
            lines.append(f"### gate {result.number} {result.title}: {check.name}")
            lines.append("")
            lines.append(check.detail or "(no detail)")
            if check.command:
                lines.append("")
                lines.append("```")
                lines.append(_readable(check.command, versions))
                lines.append("```")
            lines.append("")

    lines.append("## Every check")
    lines.append("")
    for result in results:
        lines.append(f"### Gate {result.number}: {result.title}")
        if result.note:
            lines.append("")
            lines.append(result.note)
        lines.append("")
        if result.skipped:
            lines.append("Not run.")
            lines.append("")
            continue
        lines.append("| Check | Result | Detail |")
        lines.append("|---|---|---|")
        for check in result.checks:
            detail = (check.detail or "").replace("\n", " ").replace("|", "\\|")
            lines.append(f"| {check.name} | {'pass' if check.ok else '**FAIL**'} "
                         f"| {detail[:400]} |")
        lines.append("")
        lines.extend(_per_tool_tables(result))
        commands = [c.command for c in result.checks if c.command]
        if commands:
            lines.append("Commands:")
            lines.append("")
            lines.append("```bash")
            for item in dict.fromkeys(_readable(c, versions) for c in commands):
                lines.append(item)
            lines.append("```")
            lines.append("")

    lines.append("## Versions and hashes")
    lines.append("")
    lines.append("| | |")
    lines.append("|---|---|")
    for key, value in _hash_rows(versions):
        lines.append(f"| {key} | `{value}` |")
    lines.append(f"| streamlit_stubbed | `{versions.get('streamlit_stubbed')}` |")
    lines.append(f"| STAR-Bench working tree | "
                 f"`{'dirty' if versions.get('star_bench_dirty') else 'clean'}` |")
    lines.append(f"| STAR-Bench-Web working tree | "
                 f"`{'dirty' if versions.get('platform_dirty') else 'clean'}` |")
    lines.append(f"| interpreter | `{versions.get('python')}` |")
    if versions.get("platform_python") != versions.get("python"):
        lines.append(f"| platform interpreter | `{versions.get('platform_python')}` |")
    lines.append("")
    libraries = versions.get("library_versions") or {}
    if libraries:
        lines.append("Tool-layer libraries: "
                     + ", ".join(f"{k} {v}" for k, v in sorted(libraries.items())) + ".")
        lines.append("")

    lines.append("## Before a rerun")
    lines.append("")
    lines.append("```bash")
    lines.append("cd " + str(versions.get("star_bench_root") or "STAR-Bench"))
    lines.append("python -m _experiments.scripts.preflight.run --all --report")
    lines.append("# then, on the serving host, once the model is downloaded and served:")
    lines.append("python -m _experiments.scripts.preflight.run canary --config <config id> \\")
    lines.append("    --base-url http://127.0.0.1:11434/v1")
    lines.append("```")
    lines.append("")

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
